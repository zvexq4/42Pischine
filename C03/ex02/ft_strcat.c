#include <stdio.h>

char	*ft_strcat(char *dest, char *src)
{
	int		i;
	int		j;

	i = 0;
	j = 0;
	while (dest[i] != '\0')
		i++;
	while (src[j])
	{
		dest[i] = src[j];
		i++;
		j++;
	}
	dest[i] = '\0';
	return(dest);
}

int main(void)
{
	char dest[50] = "merhaba";
	char src[] = "dünya";
	printf("%s\n",ft_strcat(dest,src));
}